from __future__ import annotations

from typing import TYPE_CHECKING, Any

from scrapebadger.account.models import WebhookDeliveries, WebhookSecret

if TYPE_CHECKING:
    from scrapebadger._internal.client import BaseClient


class AccountClient:
    """Client for the Account API.

    Example:
        ```python
        async with ScrapeBadger(api_key="your-key") as client:
            secret = await client.account.webhook_secret()
            recent = await client.account.webhook_deliveries(limit=20)
            for d in recent.deliveries:
                print(d.request_id, d.state, d.attempts, d.last_status)
        ```

    Note:
        This client is not instantiated directly. Instead, access it through
        the `account` property of the main `ScrapeBadger` client.
    """

    def __init__(self, client: BaseClient) -> None:
        self._client = client

    async def webhook_secret(self) -> WebhookSecret:
        """Get the secret that signs this account's webhooks. Free.

        Created on first read. Verify each delivery with
        ``scrapebadger.webhooks.verify_signature(secret.secret, raw_body, signature)``.

        Returns:
            WebhookSecret with ``secret``.

        Raises:
            PermissionDeniedError: The key is limited to some APIs (403
                ``full_access_required``); the secret needs a full-access key.
        """
        response = await self._client.get("/v1/account/webhook-secret")
        return WebhookSecret.model_validate(response)

    async def rotate_webhook_secret(self) -> WebhookSecret:
        """Replace the webhook signing secret. Free.

        Deliveries that start from now on are signed with the new secret;
        retries of a delivery already under way keep the old one, so accept
        both for a few minutes after rotating.

        Returns:
            WebhookSecret with the new ``secret``.

        Raises:
            PermissionDeniedError: The key is limited to some APIs (403
                ``full_access_required``).
        """
        response = await self._client.post("/v1/account/webhook-secret/rotate")
        return WebhookSecret.model_validate(response)

    async def webhook_deliveries(self, limit: int = 50) -> WebhookDeliveries:
        """List the account's webhook deliveries of the last 24 hours, newest first. Free.

        Args:
            limit: How many to return (1-200, default 50).

        Returns:
            WebhookDeliveries with ``deliveries`` and ``window_hours``.

        Raises:
            PermissionDeniedError: The key is limited to some APIs (403
                ``full_access_required``).
        """
        response = await self._client.get("/v1/account/webhook-deliveries", params={"limit": limit})
        return WebhookDeliveries.model_validate(response)

